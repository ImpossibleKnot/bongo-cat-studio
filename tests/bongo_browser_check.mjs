const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output=new URL('../build/',import.meta.url).pathname;
import fs from 'node:fs';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const page=await browser.newPage({viewport:{width:1120,height:1250},acceptDownloads:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8766/');
await page.getByRole('button',{name:'Switch on',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#start').hidden);
await page.getByRole('button',{name:'Harmony',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('[data-page="1"]').getAttribute('aria-pressed')==='true');
if(await page.locator('[data-knob-caption="2"]').textContent()!=='CHORDS')throw new Error('Dynamic labels failed');
await page.getByRole('button',{name:'Looper',exact:true}).click();
await page.getByLabel('Metronome',{exact:true}).selectOption('2');
await page.waitForTimeout(200);
const knob4=page.getByRole('slider',{name:'KNOB 4',exact:true});
await knob4.focus();await page.keyboard.press('ArrowDown');await page.keyboard.press('ArrowDown');
await page.waitForFunction(()=>document.querySelector('#metronome').value==='0');
await page.screenshot({path:output+'bongo-browser-looper-0.4.0-rc1.png'});
await page.getByRole('button',{name:'Dress up',exact:true}).click();
await page.getByRole('slider',{name:'KNOB 1',exact:true}).focus();await page.keyboard.press('ArrowUp');await page.keyboard.press('ArrowUp');
await page.getByRole('slider',{name:'KNOB 2',exact:true}).focus();for(let i=0;i<5;i++)await page.keyboard.press('ArrowUp');
await page.getByRole('slider',{name:'KNOB 3',exact:true}).focus();await page.keyboard.press('ArrowUp');await page.keyboard.press('ArrowUp');
await page.waitForTimeout(400);
await page.screenshot({path:output+'bongo-browser-dressup-0.4.0-rc1.png'});
await page.getByRole('button',{name:'Mixer',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('[data-page="3"]').getAttribute('aria-pressed')==='true');
const fx=await page.getByRole('button',{name:'FX / FILL',exact:true}).boundingBox();
await page.mouse.move(fx.x+fx.width/2,fx.y+fx.height/2);await page.mouse.down();
await page.waitForTimeout(350);
const partyA=await page.locator('canvas').evaluate(c=>c.toDataURL());
await page.screenshot({path:output+'bongo-browser-maximum-cat-0.4.0-rc1.png'});
await page.waitForTimeout(190);
const partyB=await page.locator('canvas').evaluate(c=>c.toDataURL());
if(partyA===partyB)throw new Error('Maximum Cat animation froze without live notes');
await page.mouse.up();await page.waitForTimeout(200);
if(await page.locator('[data-page="3"]').getAttribute('aria-pressed')!=='true')throw new Error('Maximum Cat changed the selected page');
await page.getByRole('button',{name:'Studio',exact:true}).click();
await page.getByRole('button',{name:'Record WAV',exact:true}).click();
await page.getByRole('button',{name:'Play a demo jam ↗',exact:true}).click();
await page.waitForTimeout(6000);
await page.screenshot({path:output+'bongo-browser-playing-0.4.0-rc1.png'});
const downloadPromise=page.waitForEvent('download');
await page.getByRole('button',{name:'Stop & save WAV',exact:true}).click();
const download=await downloadPromise;
await download.saveAs(output+'bongo-browser-performance-0.4.0-rc1.wav');
await page.getByRole('button',{name:'Stop demo',exact:true}).click();
await page.reload();await page.getByRole('button',{name:'Switch on',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#start').hidden);
if(await page.getByLabel('Metronome',{exact:true}).inputValue()!=='0')throw new Error('Reload click not OFF');
if(errors.length)throw new Error(errors.join('\n'));
console.log('PASS: browser boots, page navigation, dynamic knob labels, hardware-style click control, costumes, live demo, WAV download and quiet reload. No JS errors.');
await browser.close();
